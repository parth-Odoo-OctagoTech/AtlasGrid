function haversineDistanceKm(lat1, lon1, lat2, lon2) {
  const R = 6371;
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLon = ((lon2 - lon1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((lat1 * Math.PI) / 180) *
      Math.cos((lat2 * Math.PI) / 180) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return parseFloat((R * c).toFixed(1));
}

// 1. Process Power Plants
const plantsFilePath = path.join(process.cwd(), 'data', 'power-plants.json');
let existingPlants = [];
if (fs.existsSync(plantsFilePath)) {
  existingPlants = JSON.parse(fs.readFileSync(plantsFilePath, 'utf-8'));
}

// Filter out old NP plants if any
const nonNpPlants = existingPlants.filter(p => !p.id.startsWith("np-plant-") && p.country !== "NP");
const mergedPlants = [...nonNpPlants, ...NEPAL_POWER_PLANTS];

fs.writeFileSync(plantsFilePath, JSON.stringify(mergedPlants, null, 2), 'utf-8');
console.log(`✓ Updated data/power-plants.json: Total plants = ${mergedPlants.length} (Added ${NEPAL_POWER_PLANTS.length} Nepal plants)`);

// 2. Cross-reference Nepal Data Centers with Nepal Power Plants
const enrichedNepalDcs = NEPAL_DATACENTERS.map(dc => {
  const nearbyPlants = mergedPlants
    .map(p => ({ plant: p, dist: haversineDistanceKm(dc.latitude, dc.longitude, p.latitude, p.longitude) }))
    .sort((a, b) => a.dist - b.dist)
    .slice(0, 10);

  let cleanCap = 0;
  let totalCap = 0;
  let weightedCo2Sum = 0;

  for (const item of nearbyPlants) {
    totalCap += item.plant.capacityMw;
    weightedCo2Sum += (item.plant.co2IntensityGPerKwh || 15) * item.plant.capacityMw;
    if (["nuclear", "hydro", "solar", "wind", "geothermal", "storage"].includes(item.plant.fuelType)) {
      cleanCap += item.plant.capacityMw;
    }
  }

  const cleanPercent = totalCap > 0 ? parseFloat(((cleanCap / totalCap) * 100).toFixed(1)) : 98.5;
  const avgCo2 = totalCap > 0 ? Math.round(weightedCo2Sum / totalCap) : 16;
  const annualEnergyMwh = dc.estimatedPowerMw * 8760 * (dc.pue || 1.4);
  const estimatedAnnualCo2Tons = Math.round((annualEnergyMwh * avgCo2 * 1000) / 1000000);

  return {
    ...dc,
    localCleanEnergyPercent: cleanPercent,
    estimatedAnnualCo2Tons: estimatedAnnualCo2Tons
  };
});

